/// Способ установки PWA, доступный текущему браузеру, — от него зависит
/// содержимое модалки промо (`pwa_install_promo`).
enum PwaInstallMethod {
  /// Chromium (Chrome/Edge на десктопе и Android): перехвачен
  /// `beforeinstallprompt` — показываем кнопку «Установить» с нативным
  /// диалогом браузера.
  nativePrompt,

  /// iOS/iPadOS: нативного диалога нет ни у одного браузера (все на WebKit) —
  /// пошаговая инструкция «Поделиться → На экран „Домой“».
  iosShareSheet,

  /// Прочие браузеры (Firefox, десктопный Safari и т.п.): универсальная
  /// подсказка про меню браузера.
  manual,
}
